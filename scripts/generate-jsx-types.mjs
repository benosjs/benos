/* global console, process */
import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { listAll } from '@webref/elements'
import { format } from 'prettier'

const require = createRequire(import.meta.url)
const { aria } = require('aria-query')
const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const idlRoot = join(root, 'node_modules', '@webref', 'idl')
const domTypes = await readFile(
  require.resolve('typescript/lib/lib.dom.d.ts'),
  'utf8',
)

const standard = await listAll()
const records = [
  ...(standard.html?.elements ?? []).map((element) => ({
    ...element,
    family: 'html',
  })),
  ...(standard.SVG2?.elements ?? []).map((element) => ({
    ...element,
    family: 'svg',
  })),
  ...(standard['mathml-core']?.elements ?? []).map((element) => ({
    ...element,
    family: 'mathml',
  })),
]

const interfaceNames = new Set(
  [...domTypes.matchAll(/^interface\s+(\w+)/gm)].map((match) => match[1]),
)
const idlFiles = [
  'html.idl',
  'dom.idl',
  'SVG.idl',
  'mathml-core.idl',
  'wai-aria.idl',
]
const idlText = (
  await Promise.all(
    idlFiles.map((file) => readFile(join(idlRoot, file), 'utf8')),
  )
).join('\n')
const attributes = new Set(['class'])
for (const match of idlText.matchAll(/Reflect="([^"]+)"/g))
  attributes.add(match[1])
for (const match of idlText.matchAll(
  /^\s*(?:\[[^\]]+\]\s*)?(?:readonly\s+)?attribute\s+[^;\n]*?\s([A-Za-z][A-Za-z0-9]*)\s*;/gm,
)) {
  const name = match[1]
  if (name === 'children' || name === 'style' || name === 'ref') continue
  if (name === 'className') attributes.add('class')
  else if (name === 'htmlFor') attributes.add('for')
  else if (!name.startsWith('aria') && !name.startsWith('on'))
    attributes.add(name)
}
for (const name of aria.keys()) attributes.add(name)
attributes.delete('className')
attributes.delete('htmlFor')

const eventMap = new Map()
const eventSection = domTypes.match(
  /interface GlobalEventHandlersEventMap \{([\s\S]*?)\n\}/,
)
for (const match of eventSection?.[1]?.matchAll(/"([^"]+)":\s*([^;]+);/g) ?? [])
  eventMap.set(match[1], match[2].trim())

function eventProp(name) {
  if (name === 'dblclick') return 'onDblClick'
  const words = name.split(/[-:]/g)
  const suffix = words
    .map((word) => `${word[0]?.toUpperCase() ?? ''}${word.slice(1)}`)
    .join('')
  return `on${suffix}`
}

function interfaceFor(record) {
  return interfaceNames.has(record.interface)
    ? `globalThis.${record.interface}`
    : record.family === 'svg'
      ? 'globalThis.SVGElement'
      : record.family === 'mathml'
        ? 'globalThis.MathMLElement'
        : 'globalThis.HTMLElement'
}

function quote(name) {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`
}

const attributeLines = [...attributes]
  .sort()
  .map((name) => `  ${quote(name)}?: StandardAttributeValue`)
const ariaLines = [...aria.keys()]
  .sort()
  .map((name) => `  '${name}'?: StandardAttributeValue`)
const eventLines = [...eventMap.entries()]
  .sort(([left], [right]) => left.localeCompare(right))
  .map(([name, type]) => `  ${eventProp(name)}?: EventHandler<${type}, T>`)

const intrinsic = new Map()
for (const record of records) {
  const existing = intrinsic.get(record.name)
  if (!existing || existing.family === 'mathml')
    intrinsic.set(record.name, record)
}
const intrinsicLines = [...intrinsic.entries()]
  .sort(([left], [right]) => left.localeCompare(right))
  .map(
    ([name, record]) =>
      `  ${quote(name)}: Generated${record.family[0].toUpperCase()}${record.family.slice(1)}<${interfaceFor(record)}>`,
  )

const output = `// Generated by scripts/generate-jsx-types.mjs from @webref/elements, @webref/idl, aria-query, and TypeScript's lib.dom.d.ts.\n// Do not edit by hand.\nimport type { Child } from './index.js'\n\nexport type StandardAttributeValue = string | number | boolean | null | undefined\nexport type Style = string | Readonly<Record<string, string | number | null | undefined>>\nexport type EventHandler<E extends Event, T extends globalThis.Element> = (\n  event: E & { currentTarget: T },\n) => unknown\n\nexport interface GeneratedAriaAttributes {\n${ariaLines.join('\n')}\n}\n\nexport interface GeneratedAttributes<T extends globalThis.Element>\n  extends GeneratedAriaAttributes {\n${attributeLines.join('\n')}\n  [name: \`data-\${string}\`]: StandardAttributeValue\n  style?: Style\n  ref?: (element: T) => void\n  children?: Child\n}\n\nexport type GeneratedHtml<T extends globalThis.Element> = GeneratedAttributes<T> & {\n${eventLines.join('\n')}\n}\nexport type GeneratedSvg<T extends globalThis.Element> = GeneratedHtml<T>\nexport type GeneratedMathml<T extends globalThis.Element> = GeneratedHtml<T>\n\nexport interface GeneratedIntrinsicElements {\n${intrinsicLines.join('\n')}\n}\n`

const formatted = await format(output, {
  parser: 'typescript',
  singleQuote: true,
  semi: false,
  trailingComma: 'all',
})
const destination = join(root, 'packages/dom/src/generated-jsx.ts')
if (process.argv.includes('--check')) {
  const current = await readFile(destination, 'utf8').catch(() => '')
  if (current !== formatted) {
    console.error(
      'Generated JSX types are stale. Run node scripts/generate-jsx-types.mjs.',
    )
    process.exit(1)
  }
  console.log('Generated JSX types are up to date.')
} else {
  await writeFile(destination, formatted)
}
